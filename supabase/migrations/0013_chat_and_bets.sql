-- Channels, messages and shared bets.
--
-- The feed was a read-only ledger of generated events. This turns it into
-- somewhere people actually talk: league channels with text, images and GIFs,
-- direct messages between friends, and bet slips shared from a sportsbook.
--
-- Three things are worth explaining before the DDL.
--
-- 1. Membership is modelled twice on purpose. A league channel is readable by
--    anyone in the league, so there is no row to create when somebody joins —
--    `channel_members` exists only for direct messages, where the participant
--    list IS the access rule. `channel_reads` is separate again, because unread
--    state is per-person on every channel including the implicit ones.
--
-- 2. A DM has a `dm_key`: the two user ids sorted and joined. Without it, two
--    people opening a conversation at the same moment create two conversations
--    and each sees half the messages. The key is generated by a trigger from
--    the members, not supplied by the client.
--
-- 3. Uploads are not writable by users. The bucket is public to read so an
--    <img> works without a signed URL round trip, and every write goes through
--    the API route with the service role, which is the only place file type and
--    size are checked. A browser-side upload policy would move that check to
--    somewhere a client can skip.

-- Enums ----------------------------------------------------------------------

do $$
begin
  if not exists (select 1 from pg_type where typname = 'channel_kind') then
    create type channel_kind as enum ('league', 'mode', 'dm');
  end if;
  if not exists (select 1 from pg_type where typname = 'message_kind') then
    create type message_kind as enum ('text', 'image', 'bet_slip', 'system');
  end if;
  if not exists (select 1 from pg_type where typname = 'bet_stance') then
    create type bet_stance as enum ('tail', 'fade');
  end if;
end
$$;

-- Channels -------------------------------------------------------------------

create table if not exists public.channels (
  id uuid primary key default gen_random_uuid(),
  kind channel_kind not null default 'league',
  league_id uuid references public.leagues (id) on delete cascade,
  -- Set when the channel belongs to a game mode, so a mode page can open its
  -- own room: 'pickem', 'survivor', 'td', 'h2h', 'playground'.
  mode text,
  name text not null,
  topic text,
  emoji text,
  dm_key text unique,
  is_default boolean not null default false,
  position integer not null default 0,
  created_by uuid references public.profiles (user_id) on delete set null,
  last_message_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint channels_name_len check (char_length(name) between 1 and 40),
  constraint channels_topic_len check (topic is null or char_length(topic) <= 200),
  -- A league or mode channel must name its league; a DM must not.
  constraint channels_league_scope check (
    (kind = 'dm' and league_id is null and dm_key is not null)
    or (kind <> 'dm' and league_id is not null and dm_key is null)
  ),
  constraint channels_mode_scope check ((kind = 'mode') = (mode is not null))
);

create index if not exists channels_league_idx on public.channels (league_id, position);
create index if not exists channels_recent_idx on public.channels (last_message_at desc nulls last);
create unique index if not exists channels_one_per_mode_idx
  on public.channels (league_id, mode) where mode is not null;

create trigger channels_touch before update on public.channels
  for each row execute function public.touch_updated_at();

create table if not exists public.channel_members (
  channel_id uuid not null references public.channels (id) on delete cascade,
  user_id uuid not null references public.profiles (user_id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (channel_id, user_id)
);

create index if not exists channel_members_user_idx on public.channel_members (user_id);

create table if not exists public.channel_reads (
  channel_id uuid not null references public.channels (id) on delete cascade,
  user_id uuid not null references public.profiles (user_id) on delete cascade,
  last_read_at timestamptz not null default now(),
  primary key (channel_id, user_id)
