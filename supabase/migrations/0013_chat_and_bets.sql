-- Opening a room ------------------------------------------------------------
--
-- Both of these are SECURITY DEFINER and both exist for the same reason: the
-- channel row and the rows that give access to it have to appear together.
--
-- A DM cannot be inserted by a client at all. `channels_league_scope` requires
-- dm_key, dm_key is derived from the participants, and the participants live in
-- a second table — so a client-side insert would either fail the constraint or
-- leave a conversation nobody can read. Routing it through a function also
-- makes the race harmless: two people tapping "message" at the same instant
-- collide on the dm_key unique index and both get the same conversation.

create or replace function public.open_dm(other_user uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  me uuid := auth.uid();
  key text;
  existing uuid;
  created uuid;
begin
  if me is null then
    raise exception 'not signed in';
  end if;
  if other_user is null or other_user = me then
    raise exception 'pick somebody else';
  end if;
  if not exists (select 1 from public.profiles p where p.user_id = other_user) then
    raise exception 'no such person';
  end if;

  key := array_to_string(array(select unnest(array[me, other_user]) order by 1), ':');

  select id into existing from public.channels where dm_key = key;
  if existing is not null then
    -- Rejoin a conversation someone left, rather than starting a second one.
    insert into public.channel_members (channel_id, user_id)
    values (existing, me), (existing, other_user)
    on conflict do nothing;
    return existing;
  end if;

  insert into public.channels (kind, name, dm_key, created_by)
  values ('dm', 'Direct message', key, me)
  on conflict (dm_key) do nothing
  returning id into created;

  if created is null then
    select id into created from public.channels where dm_key = key;
  end if;

  insert into public.channel_members (channel_id, user_id)
  values (created, me), (created, other_user)
  on conflict do nothing;

  return created;
end
$$;

revoke all on function public.open_dm(uuid) from public;
grant execute on function public.open_dm(uuid) to authenticated;

-- A mode's room is created the first time somebody opens it, so a league does
-- not start life with five empty channels it never uses.

create or replace function public.ensure_mode_channel(target_league uuid, target_mode text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  existing uuid;
  created uuid;
  label text;
  mark text;
begin
  if not public.is_league_member(target_league) then
    raise exception 'not a member of that league';
  end if;

  select id into existing
  from public.channels
  where league_id = target_league and mode = target_mode;
  if existing is not null then
    return existing;
  end if;

  select l, e into label, mark from (
    values
      ('pickem', 'pickem', '🎯'),
      ('survivor', 'survivor', '🛡️'),
      ('td', 'td-scorer', '🏈'),
      ('h2h', 'head-to-head', '⚔️'),
      ('playground', 'playground', '🎲')
  ) as m(k, l, e)
  where m.k = target_mode;

  if label is null then
    raise exception 'unknown mode %', target_mode;
  end if;

  insert into public.channels (kind, league_id, mode, name, topic, emoji, position, created_by)
  values ('mode', target_league, target_mode, label, 'Talk about this mode.', mark, 10, auth.uid())
  on conflict (league_id, mode) do nothing
  returning id into created;

  if created is null then
    select id into created from public.channels
    where league_id = target_league and mode = target_mode;
  end if;

  return created;
end
$$;

revoke all on function public.ensure_mode_channel(uuid, text) from public;
grant execute on function public.ensure_mode_channel(uuid, text) to authenticated;

-- A channel's shape is fixed once created -----------------------------------

create or replace function public.enforce_channel_identity()
returns trigger
language plpgsql
as $$
begin
  if new.kind <> old.kind then
    raise exception 'a channel cannot change kind';
  end if;
  if new.league_id is distinct from old.league_id then
    raise exception 'a channel cannot move between leagues';
  end if;
  if new.dm_key is distinct from old.dm_key and old.dm_key is not null then
    raise exception 'a direct message cannot change participants';
  end if;
  return new;
end
$$;

drop trigger if exists channels_identity on public.channels;
create trigger channels_identity before update on public.channels
  for each row execute function public.enforce_channel_identity();

-- A message's provenance is fixed once sent ----------------------------------
--
-- Editing is allowed, and says so with edited_at. What is not allowed is
-- moving a message to another channel, reassigning its author, or swapping the
-- bet slip under a post people already tailed.

create or replace function public.enforce_message_immutability()
returns trigger
language plpgsql
as $$
begin
  if new.channel_id <> old.channel_id then
    raise exception 'a message cannot move between channels';
  end if;
  if new.user_id is distinct from old.user_id then
    raise exception 'a message cannot change author';
  end if;
  if new.kind <> old.kind then
    raise exception 'a message cannot change kind';
  end if;
  if new.bet_id is distinct from old.bet_id then
    raise exception 'a message cannot change which bet it shares';
  end if;
  if new.attachment_url is distinct from old.attachment_url and new.deleted_at is null then
    raise exception 'a message cannot change its attachment';
  end if;
  if new.created_at <> old.created_at then
    raise exception 'a message cannot change when it was sent';
  end if;
  if old.deleted_at is not null and new.deleted_at is null then
    raise exception 'a deleted message cannot be restored';
  end if;
  return new;
end
$$;

drop trigger if exists messages_immutable on public.messages;
create trigger messages_immutable before update on public.messages
  for each row execute function public.enforce_message_immutability();

-- Keep the channel's recency current, so the list can sort by activity -------

create or replace function public.touch_channel_activity()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.channels
  set last_message_at = new.created_at
  where id = new.channel_id
    and (last_message_at is null or last_message_at < new.created_at);
  return new;
end
$$;

drop trigger if exists messages_touch_channel on public.messages;
create trigger messages_touch_channel after insert on public.messages
  for each row execute function public.touch_channel_activity();

-- Access ---------------------------------------------------------------------

create or replace function public.can_access_channel(target_channel uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.channels c
    where c.id = target_channel
      and (
        case
          when c.kind = 'dm' then exists (
            select 1 from public.channel_members m
            where m.channel_id = c.id and m.user_id = auth.uid()
          )
          else public.is_league_member(c.league_id)
        end
      )
  );
$$;

