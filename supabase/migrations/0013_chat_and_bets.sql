-- One pot per mode -----------------------------------------------------------
--
-- A pot was league-wide, which made it a page of its own and meant survivor and
-- pick'em shared one buy-in. `competition_type` was always on the table; this
-- makes it the identity, so each mode carries its own.

do $$
declare
  duplicates integer;
begin
  select count(*) into duplicates from (
    select league_id, season, competition_type
    from public.pots
    where league_id is not null
    group by league_id, season, competition_type
    having count(*) > 1
  ) d;

  if duplicates > 0 then
    raise exception
      'cannot make pots unique per mode: % league/season/mode combinations have more than one pot. Merge them first.',
      duplicates;
  end if;
end
$$;

create unique index if not exists pots_one_per_mode_idx
  on public.pots (league_id, season, competition_type)
  where league_id is not null;

