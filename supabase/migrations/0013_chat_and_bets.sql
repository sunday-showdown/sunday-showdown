  -- Every kind has to carry its own payload, or the client renders an empty row.
  constraint messages_payload check (
    deleted_at is not null
    or (kind = 'text' and body is not null)
    or (kind = 'image' and attachment_url is not null)
    or (kind = 'bet_slip' and bet_id is not null)
    or kind = 'system'
  ),
  constraint messages_attachment_dims check (
    (attachment_width is null or attachment_width between 1 and 20000)
    and (attachment_height is null or attachment_height between 1 and 20000)
  ),
  constraint messages_no_self_reply check (reply_to_id is null or reply_to_id <> id)
);

